"""Recipes — an ordered list of steps, and the loop that runs it.

A recipe is the workflow's authored artefact: the sequence of operations a model
is put through, held as data so it can be inspected, edited, diffed, re-run and
handed on.  It is deliberately **just a list**: steps run in the order written
and no dependency graph is inferred, which is the same choice the analysis layer
makes — results are composed explicitly by the caller, not by machinery.

There are two serialisations of one meaning:

* :meth:`Recipe.to_dict` / :meth:`Recipe.from_dict` (and :meth:`Recipe.to_json`
  / :meth:`Recipe.from_json`) is the **editable form** — a plain tree of
  strings, numbers, lists and mappings.  It is what the GUI's pipeline panel
  reads and writes, and it round-trips losslessly.
* :meth:`Recipe.to_python` emits the same recipe as a **runnable script**, so a
  workflow assembled by clicking can be taken away as code.

The model a recipe prepares is never mutated by the run: a step that edits
properties copies it first (see
:mod:`fea_toolkit.workflow.verbs.scale_sections`).
"""

import contextlib
import copy
import json
from dataclasses import dataclass, field, replace
from pprint import pformat
from typing import Any, Optional

from ..model.named_selection import resolve_named_selections
from ..model.selection import Selection
from .steps import DocumentState

__all__ = ["Recipe", "RecipeRun", "run_recipe", "satisfied_kinds"]

_HEADER = '"""A workflow recipe, generated by fea_toolkit.workflow."""'


def _step_to_dict(step: Any) -> dict:
    """Serialise one step, keeping an absent selection distinct from an empty one.

    Args:
        step: The :class:`~fea_toolkit.workflow.steps.Step` to serialise.

    Returns:
        A JSON-native mapping.  ``selection`` is the selection expression, or
        ``None`` for "no selection at all" — an empty *expression* stays ``""``,
        because the two mean different things to a verb.  ``enabled`` is always
        written (like ``optional``); ``status`` only when non-empty, so an
        untouched recipe stays a list of ``verb``/``selection``/``params``.
    """
    data = {
        "verb": step.verb,
        "selection": step.selection.to_string() if step.selection is not None else None,
        "params": copy.deepcopy(step.params),
        "optional": bool(step.optional),
        "enabled": bool(step.enabled),
    }
    if step.status:
        data["status"] = str(step.status)
    return data


def _strip_run_state(data: dict) -> dict:
    """Drop the run-state keys from a recipe's dict form.

    ``enabled`` / ``status`` are the *editable* form's run state; the
    :meth:`Recipe.to_python` script is an *authoring* artefact and should
    describe what the recipe does, not how its last run went — so the exported
    ``RECIPE`` is written with every step enabled and its status reset.
    """
    steps = []
    for step in data.get("steps") or []:
        steps.append({k: v for k, v in step.items() if k not in ("enabled", "status")})
    return {"name": data.get("name", ""), "steps": steps}


def _migrate_step_params(verb: str, params: dict) -> dict:
    """Normalise legacy parameter spellings before a step is validated.

    ``build_model``'s storey count was renamed from ``stories`` to ``n_stories``;
    a recipe saved against the old spelling must still load, and the migrated
    value is returned under the canonical name so the rebuilt step round-trips
    to the new form.

    Args:
        verb: The step's verb.
        params: The step's parameters as read from the recipe, before coercion.

    Returns:
        The parameters with any legacy names migrated.

    Raises:
        ValueError: If a step supplies both spellings of a renamed parameter
            with different values — that document cannot be migrated losslessly.
    """
    if verb != "build_model":
        return params
    if "stories" in params and "n_stories" in params:
        if params["stories"] != params["n_stories"]:
            raise ValueError(
                "build_model: 'stories' and 'n_stories' conflict "
                f"({params['stories']!r} vs {params['n_stories']!r}); remove one"
            )
        # Both present and equal: drop the legacy spelling.
        return {k: v for k, v in params.items() if k != "stories"}
    if "stories" in params:
        return {
            **{k: v for k, v in params.items() if k != "stories"},
            "n_stories": params["stories"],
        }
    return params


def satisfied_kinds(steps: Any, *, initial: Any = ()) -> set:
    """The kinds produced by *steps* in order, without validating ``needs``.

    The one ordering vocabulary the palette and the validator share: a linear
    scan (no graph, no topo-sort) accumulates each step's ``kind``; a geometry
    step invalidates the solved-case / modal / figure results a previous
    topology produced, and an ``open`` / ``close`` / ``build_model`` step
    clears them all — exactly as :func:`run_recipe` does.  A ``save`` step
    changes nothing.

    Args:
        steps: An iterable of steps (or a :class:`Recipe`).
        initial: Kinds available before the first step (e.g. ``{"geometry"}``
            when a prepared topology already exists).

    Returns:
        The set of kinds satisfied after the last step.
    """
    from .registry import STEP_SPECS
    from .steps import CASES, FIGURE, GEOMETRY, MODAL, SESSION

    produced = set(initial)
    for step in steps:
        if not getattr(step, "enabled", True):
            continue
        spec = STEP_SPECS.get(getattr(step, "verb", ""))
        if spec is None:
            continue
        produced.add(spec.kind)
        if spec.kind == GEOMETRY:
            produced.difference_update((CASES, MODAL, FIGURE))
        elif spec.kind == SESSION and spec.resets_document:
            # ``open`` / ``close`` / ``build_model`` replace or close the working
            # document, so the kinds a previous document produced no longer hold —
            # mirroring ``run_recipe``'s reset (a ``save`` step keeps them).
            produced.clear()
    return produced


@dataclass
class Recipe:
    """An ordered list of steps, with a name for display and provenance.

    Attributes:
        steps: The steps, in run order.
        name: Display name, e.g. ``"Admin Building — gravity"``.
    """

    steps: list = field(default_factory=list)
    name: str = ""

    def add(
        self,
        verb: str,
        selection: Any = None,
        params: Optional[dict] = None,
        *,
        optional: bool = False,
    ) -> Any:
        """Append a step and return it.

        Args:
            verb: The verb to add; must be a key of ``STEP_SPECS``.
            selection: The elements the step acts on, or ``None`` for all.
            params: Verb parameters; omissions take their declared defaults.
            optional: Whether a failure of this step should be tolerated.

        Returns:
            The appended :class:`~fea_toolkit.workflow.steps.Step`.

        Raises:
            ValueError: If *verb* is unknown, or a parameter is undeclared or
                has the wrong type.
        """
        from .registry import STEP_SPECS
        from .steps import Step

        if verb not in STEP_SPECS:
            raise ValueError(f"unknown verb {verb!r}; known verbs: {sorted(STEP_SPECS)}")
        # Type-check now, so a mistake surfaces where it was made rather than
        # at the end of a long run.
        STEP_SPECS[verb].validate(params or {})
        step = Step(verb=verb, selection=selection, params=dict(params or {}), optional=optional)
        self.steps.append(step)
        return step

    def set_enabled(self, index: int, enabled: bool) -> None:
        """Set a step's ``enabled`` flag; enabling cascades to its precursors.

        Checking a step means "run this", so every step it *needs* must run too:
        the transitive :attr:`~fea_toolkit.workflow.steps.StepSpec.needs` closure
        is walked backwards and each disabled precursor is enabled.  Unchecking
        does **not** cascade — disabling a step only ever removes work, never
        adds it.

        A precursor is matched by the *kind* it produces (the same set
        :func:`run_recipe` tracks), so a recipe with several steps of one kind
        enables the nearest earlier producer.

        Args:
            index: Zero-based step position in the recipe.
            enabled: The new run flag.

        Raises:
            IndexError: If *index* is out of range.
        """
        from dataclasses import replace

        from .registry import STEP_SPECS

        if not 0 <= index < len(self.steps):
            raise IndexError(f"step index {index} out of range")

        def _enable_precursors(i: int, seen: Optional[set[int]] = None) -> None:
            if seen is None:
                seen = set()
            if i in seen:
                return
            seen.add(i)
            spec = STEP_SPECS.get(self.steps[i].verb)
            if spec is None:
                return
            for need in spec.needs:
                for j in range(i - 1, -1, -1):
                    candidate = self.steps[j]
                    producer = STEP_SPECS.get(candidate.verb)
                    if producer is not None and producer.kind == need:
                        if not candidate.enabled:
                            self.steps[j] = replace(candidate, enabled=True)
                        _enable_precursors(j, seen)
                        break

        self.steps[index] = replace(self.steps[index], enabled=enabled)
        if enabled:
            _enable_precursors(index)

    # ── Serialisation ────────────────────────────────────────────────

    def to_dict(self) -> dict:
        """The recipe as a JSON-native mapping of the edits actually made.

        Only the parameters a step sets are written, so a file stays readable
        and a round-trip is faithful — defaults are applied at run time, not
        baked into the file.

        Returns:
            ``{"name": str, "steps": [...]}``.
        """
        return {"name": self.name, "steps": [_step_to_dict(step) for step in self.steps]}

    @classmethod
    def from_dict(cls, data: dict) -> "Recipe":
        """Rebuild a recipe from :meth:`to_dict` output.

        Args:
            data: The mapping to read.  ``steps`` may be absent (an empty
                recipe); every step's verb and parameters are validated here,
                so an invalid recipe fails on load rather than mid-run.

        Returns:
            The rebuilt recipe.

        Raises:
            ValueError: If *data* is not a mapping, a step is not a mapping, a
                verb is unknown, a parameter is undeclared, or a value has the
                wrong type.
        """
        from .registry import STEP_SPECS
        from .steps import Step

        if not isinstance(data, dict):
            raise ValueError(f"a recipe must be a mapping, got {type(data).__name__}")
        steps = []
        for index, raw in enumerate(data.get("steps") or []):
            if not isinstance(raw, dict):
                raise ValueError(
                    f"recipe step {index}: expected a mapping, got {type(raw).__name__}"
                )
            verb = raw.get("verb")
            if verb not in STEP_SPECS:
                raise ValueError(
                    f"recipe step {index}: unknown verb {verb!r}; known verbs: {sorted(STEP_SPECS)}"
                )
            spec = STEP_SPECS[verb]
            given = _migrate_step_params(verb, dict(raw.get("params") or {}))
            for name, value in given.items():
                if name not in spec.params:
                    raise ValueError(
                        f"recipe step {index} ({verb}): unknown parameter {name!r}; "
                        f"expected {sorted(spec.params)}"
                    )
                spec.params[name].coerce(value, verb=verb, name=name)
            expression = raw.get("selection")
            selection = Selection.from_string(expression) if expression is not None else None
            steps.append(
                Step(
                    verb=verb,
                    selection=selection,
                    params=given,
                    optional=bool(raw.get("optional", False)),
                    enabled=bool(raw.get("enabled", True)),
                    status=str(raw.get("status", "")),
                )
            )
        return cls(steps=steps, name=str(data.get("name", "")))

    def to_json(self, path: Optional[str] = None) -> str:
        """Serialise to JSON, optionally writing it to *path*.

        Args:
            path: Where to write the JSON.  ``None`` just returns the text.

        Returns:
            The JSON text — the same text written when *path* is given.
        """
        text = json.dumps(self.to_dict(), indent=2)
        if path is not None:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(text + "\n")
        return text

    @classmethod
    def from_json(cls, path: str) -> "Recipe":
        """Read a recipe written by :meth:`to_json`.

        Args:
            path: The JSON file to read.

        Returns:
            The rebuilt recipe.

        Raises:
            ValueError: If the file does not hold a recipe, or a step is invalid.
        """
        with open(path, encoding="utf-8") as handle:
            return cls.from_dict(json.loads(handle.read()))

    def to_python(self) -> str:
        """Emit the recipe as a runnable Python script.

        The script rebuilds the same recipe through :meth:`from_dict` and runs
        it, so a workflow assembled in the GUI can be taken away as code and
        kept under version control.

        Returns:
            The script source.  It compiles (``compile()`` succeeds) and, with
            a real model path, runs.
        """
        body = pformat(_strip_run_state(self.to_dict()), width=88, sort_dicts=False)
        return (
            _HEADER
            + "\n\n"
            + "from fea_toolkit.io.s2k_parser import SAP2000Parser\n"
            + "from fea_toolkit.workflow import Recipe, run_recipe\n\n"
            + "#: The model this recipe prepares.\n"
            + 'MODEL_PATH = "model.s2k"\n\n'
            + "#: The same declarative form Recipe.to_dict() writes.\n"
            + f"RECIPE = {body}\n\n\n"
            + "def main() -> None:\n"
            + "    md = SAP2000Parser(MODEL_PATH).parse().get_model_data()\n"
            + "    run = run_recipe(Recipe.from_dict(RECIPE), md, log=print)\n"
            + "    for result in run.results:\n"
            + '        print(f"{result.kind}: {result.label}")\n\n\n'
            + 'if __name__ == "__main__":\n'
            + "    main()\n"
        )

    @classmethod
    def from_python(cls, source: str) -> "Recipe":
        """Rebuild a recipe from a :meth:`to_python` script's ``RECIPE = {…}`` literal.

        The script is **not** executed: the ``RECIPE`` assignment is parsed with
        :mod:`ast` and its value evaluated with :func:`ast.literal_eval`, so only
        a literal (the form :meth:`to_python` emits) can be imported — never
        arbitrary code.

        Args:
            source: The script source.

        Returns:
            The recipe the script's ``RECIPE`` literal describes.

        Raises:
            ValueError: If the script cannot be parsed, has no ``RECIPE = …``
                literal, or its literal value cannot be evaluated (a non-literal,
                an unhashable key, or pathological nesting) or is not a recipe
                mapping — the original parse / evaluation exception is chained
                as the cause.
        """
        import ast

        try:
            tree = ast.parse(source)
        except SyntaxError as exc:
            raise ValueError(f"invalid Python script: {exc}") from exc
        for node in tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id == "RECIPE":
                        try:
                            value = ast.literal_eval(node.value)
                        except (
                            ValueError,
                            SyntaxError,
                            TypeError,
                            MemoryError,
                            RecursionError,
                        ) as exc:
                            raise ValueError(f"RECIPE is not a literal value: {exc}") from exc
                        return cls.from_dict(value)
        raise ValueError("no RECIPE = {...} literal found in the script")

    def __len__(self) -> int:
        return len(self.steps)

    def __iter__(self):
        return iter(self.steps)


@dataclass
class RecipeRun:
    """What a recipe run produced, in step order.

    Attributes:
        results: Every :class:`~fea_toolkit.workflow.steps.StepResult` the run
            produced for the *final* document, in step order.  A step may
            contribute several.  A document-lifecycle step (``open`` / ``close``
            / ``build_model``) discards the results the previous document
            produced, so a caller never registers A's mesh / tables after B was
            opened.
        failures: ``(step index, verb, message)`` for each *optional* step that
            failed and was tolerated.  A non-optional failure does not appear
            here — it raises :class:`~fea_toolkit.workflow.steps.StepError`, so
            the run cannot end with a silently-different model.
        cancelled: Whether the run stopped early because ``cancel()`` asked it to.
    """

    results: list = field(default_factory=list)
    failures: list = field(default_factory=list)
    cancelled: bool = False
    #: ``(step index, verb, "ok" | "failed" | "cancelled" | "skipped")`` in
    #: completion order, so a caller can show which steps ran and how they ended
    #: without re-deriving it from ``results`` / ``failures`` (a successful step
    #: may produce no result, a tolerated failure appears here as well as in
    #: ``failures``, and a *disabled* step is recorded ``"skipped"``).
    step_status: list = field(default_factory=list)
    #: The working document's state after the last step, for a caller that must
    #: adopt it (the GUI).  ``None`` until the run completes.
    document: Optional[DocumentState] = None
    #: Whether a document-lifecycle step (``open`` / ``close`` / ``build_model``)
    #: replaced or closed the document mid-run, so the caller must re-adopt the
    #: document rather than keep showing the one it was handed.
    document_reset: bool = False


def _resolve_step_selection(step: Any, context: Any) -> Any:
    """Expand a step's named-selection references into explicit ids.

    A step's ``Selection.selections`` / ``exclude_selections`` fields name saved
    selections; the verb layer expands them against the document's store before
    the verb runs, so ``mesh`` / ``scale_sections`` / the check verbs see
    concrete element and node ids, never unresolved references.  A step with no
    named-selection reference is returned unchanged.
    """
    selection = step.selection
    if selection is None or not (selection.selections or selection.exclude_selections):
        return step
    resolved = resolve_named_selections(selection, context.named_selections, context.model_data)
    return replace(step, selection=resolved)


def run_recipe(
    recipe: Recipe,
    model_data: Any,
    *,
    model: Any = None,
    cancel: Any = None,
    log: Any = None,
    pipeline_log: Any = None,
    on_step: Any = None,
    on_progress: Any = None,
    opensees_python: Any = None,
    named_selections: Any = None,
) -> RecipeRun:
    """Run a recipe's steps in order against *model_data*.

    Each step sees the state the previous one left: a meshing step's topology is
    what a later analysis step solves, and an analysis step's cases are what a
    later reduction step reads.  ``cancel()`` is polled **between** steps — a
    step already running is never interrupted mid-way, matching the GUI worker's
    cooperative cancellation.  A step that stops *itself* mid-way (a solve
    cancelled between cases) records it on ``context.cancelled``, which is read
    after every step — including the last — so the run is still reported
    cancelled.

    Args:
        recipe: The steps to run.
        model_data: The parsed model to prepare.  It is not mutated: a step that
            edits properties works on a copy.  May be ``None`` for an
            archive-only recipe — one that starts with ``open_results`` — which
            rebuilds ``model_data`` (and ``model``) from the archive rather than
            a source model.
        model: An already-prepared topology to start from, if there is one.
        cancel: Zero-argument predicate; ``True`` stops the run at the next step
            boundary.  Defaults to "never cancelled".
        log: One-line sink for progress.  Defaults to discarding messages;
            when ``None`` but *pipeline_log* is given, recipe progress is
            routed through ``pipeline_log`` (step ``"workflow"``) instead.
        pipeline_log: Optional structured
            :class:`~fea_toolkit.io.log.PipelineLog` handed to analysis verbs;
            ``None`` leaves verbs to their own (``verbose``-derived) logging.
        on_step: Optional callback ``(step index, verb, status)`` called as each
            step starts (``"running"``) and finishes (``"ok"`` / ``"failed"`` /
            ``"cancelled"``), so a GUI can show live per-step progress.  A
            callback exception is swallowed — a progress listener must never
            change a step's outcome.  It is called on the caller's thread.
        on_progress: Optional fine-grained progress callback
            ``(index, name, total)`` — stored on the
            :class:`~fea_toolkit.workflow.steps.StepContext` so a solve verb can
            report each case before it solves, driving a determinate bar.  Called
            on the caller's thread; an exception is swallowed like *on_step*'s.
        opensees_python: Optional path to the interpreter that should run
            analysis out-of-process when this process cannot import
            ``openseespy`` (the "separate" build).  Stored on the
            :class:`~fea_toolkit.workflow.steps.StepContext` and read by the
            solve verbs.
        named_selections: Optional ``{name: NamedSelection}`` store to seed the
            run's context with — the GUI's window-owned selections, so a step
            whose ``Selection.selections`` field references a GUI-authored
            selection resolves it.  Copied into the context, never mutated in
            place.  ``None`` starts the run with an empty store (the ``select``
            verb still adds to it).

    Returns:
        The :class:`RecipeRun` — its results, tolerated failures and whether it
        was cancelled.

    Raises:
        StepError: If a non-optional step raises.  The error carries the step's
            index, its verb, the original exception, the partial ``step_status``
            run state, and the working document's state (``document`` /
            ``document_reset``) — so a caller that catches it can adopt a document
            a completed ``open`` / ``close`` / ``build_model`` step had replaced
            before the failure.
        ValueError: If a step names an unknown verb.
    """
    from .registry import STEP_SPECS
    from .steps import (
        CASES,
        FIGURE,
        GEOMETRY,
        MODAL,
        MODEL,
        SESSION,
        TABLE,
        StepContext,
        StepError,
    )

    context = StepContext(model_data=model_data, model=model)
    if named_selections is not None:
        context.named_selections.update(dict(named_selections))
    if cancel is not None:
        context.cancel = cancel
    if pipeline_log is not None:
        context.pipeline_log = pipeline_log
    if opensees_python is not None:
        context.opensees_python = opensees_python
    if log is not None:
        context.log = log
    elif pipeline_log is not None:
        # Merge: without an explicit one-line sink, route recipe progress
        # through the structured log so it shares one stream with the events
        # the analysis verbs emit (the GUI and the report both rely on this).
        context.log = lambda msg: pipeline_log.info("workflow", msg)
    if on_progress is not None:

        def _progress(index: int, name: str, total: int) -> None:
            # A progress listener must never change a step's outcome or stop the
            # solve — swallow its failures, exactly like ``on_step``.
            with contextlib.suppress(Exception):
                on_progress(index, name, total)

        context.progress = _progress

    # A caller-supplied topology counts as produced geometry, so a recipe may
    # start with an analysis step when run_recipe is handed an already-prepared
    # ``MeshModel``.  Every successful step adds its kind here; a step's
    # ``needs`` is validated against it before the step runs.
    produced = {GEOMETRY} if model is not None else set()

    run = RecipeRun()
    for index, step in enumerate(recipe.steps):
        if context.cancel():
            run.cancelled = True
            context.log(f"recipe: cancelled before step {index} ({step.verb})")
            break
        spec = STEP_SPECS.get(step.verb)
        if spec is None:
            raise ValueError(
                f"recipe step {index}: unknown verb {step.verb!r}; "
                f"known verbs: {sorted(STEP_SPECS)}"
            )
        missing = [kind for kind in spec.needs if kind not in produced]

        def _notify(index: int, verb: str, status: str) -> None:
            # A progress listener must never change a step's outcome, replace a
            # StepError or mask the real error — swallow its failures.
            if on_step is not None:
                with contextlib.suppress(Exception):
                    on_step(index, verb, status)

        if not step.enabled:
            # A disabled step is the user's "skip this" intent: it neither runs
            # nor has its ``needs`` validated (a precursor it lacks must not
            # stop a run that never reaches it).
            run.step_status.append((index, step.verb, "skipped"))
            _notify(index, step.verb, "skipped")
            context.log(f"recipe: step {index} ({step.verb}) skipped (disabled)")
            continue

        _notify(index, step.verb, "running")
        try:
            if missing:
                raise ValueError(
                    f"step {index} ({step.verb}) needs {missing[0]!r} — "
                    f"run a step that produces {missing[0]!r} first"
                )
            resolved_step = _resolve_step_selection(step, context)
            prior_results = len(run.results)
            run.results.extend(spec.run(context, resolved_step))
            produced.add(spec.kind)
            if spec.kind == GEOMETRY:
                # A meshing step replaced ``context.model``, so the results the
                # previous topology produced — solved cases, a modal result and
                # any chart — are stale.  Drop them from ``produced`` so a later
                # step's ``needs`` is re-validated against the new mesh, and
                # clear their context slots so nothing reads a stale payload.
                produced.difference_update((CASES, MODAL, FIGURE))
                context.case_results.clear()
                context.results.clear()
            if spec.kind == MODEL:
                # A MODEL step (isolate_base, scale_sections, …) replaced the
                # working ``SAPModelData``, so any topology prepared from the
                # previous model — and the results that depended on it — are
                # stale.  Invalidate them so a later geometry-dependent step
                # must re-mesh rather than solve a mesh of the old model, and
                # drop those stale results from ``run.results`` so a caller
                # never registers A's mesh/analysis alongside B's MODEL.  A
                # model-independent ``table`` (a ``select`` / check report)
                # survives, so a ``select → scale_sections`` recipe still shows
                # the selection report beside the new model.
                produced.difference_update((GEOMETRY, CASES, MODAL, FIGURE))
                context.model = None
                context.case_results.clear()
                context.results.clear()
                run.results[:prior_results] = [
                    r for r in run.results[:prior_results] if r.kind == TABLE
                ]
            if spec.kind == SESSION and spec.resets_document:
                # A document-lifecycle step (``open`` / ``close`` /
                # ``build_model``) replaced or closed the working document, so
                # every prior result is stale — the precursor chain starts again
                # from the new document.  A ``save`` step preserves geometry
                # availability and the solved results.  Named selections are
                # owned by the verbs themselves: ``open`` replaces the store with
                # the loaded document's, and ``close`` / ``build_model`` clear it.
                produced.clear()
                context.case_results.clear()
                context.results.clear()
                # Drop the prior document's results from ``run.results`` too, so
                # a caller (the GUI) never registers A's mesh / tables after B
                # was opened — only the current step's own result(s) and any
                # later step's results are kept.
                del run.results[:prior_results]
                run.document_reset = True
            if context.cancelled:
                # A solve cancelled between cases still completed its run;
                # record a distinct status instead of a misleading "ok".
                run.step_status.append((index, step.verb, "cancelled"))
                _notify(index, step.verb, "cancelled")
            else:
                run.step_status.append((index, step.verb, "ok"))
                _notify(index, step.verb, "ok")
        except Exception as exc:
            message = f"{type(exc).__name__}: {exc}"
            run.step_status.append((index, step.verb, "failed"))
            _notify(index, step.verb, "failed")
            if not step.optional:
                # Preserve the partial run state and the current document state on
                # the error, so a caller that catches it (the GUI's failure path)
                # can adopt a document a completed ``open`` / ``close`` /
                # ``build_model`` step had replaced, and commit the steps that
                # completed before this one rather than re-running them.
                raise StepError(
                    index,
                    step.verb,
                    exc,
                    step_status=list(run.step_status),
                    document=DocumentState(
                        model_data=context.model_data,
                        document_path=context.document_path,
                        named_selections=dict(context.named_selections),
                        model=context.model,
                    ),
                    document_reset=run.document_reset,
                ) from exc
            run.failures.append((index, step.verb, message))
            context.log(
                f"recipe: step {index} ({step.verb}) failed and is optional — continuing: {message}"
            )
        if context.cancelled:
            # A step that stopped mid-way (a solve cancelled between cases)
            # reports it on the context, so the run is marked cancelled even
            # when that step was the last one.
            run.cancelled = True
            break
    run.document = DocumentState(
        model_data=context.model_data,
        document_path=context.document_path,
        named_selections=dict(context.named_selections),
        model=context.model,
    )
    return run
