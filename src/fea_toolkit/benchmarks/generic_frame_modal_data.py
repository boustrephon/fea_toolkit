"""Transcribed modal-property tables for the IK-2005 / Medina (2002) generic
single-bay moment frames.

Source: Medina & Krawinkler (2003), PEER Report 2003/15, Appendix A,
Tables A.1--A.6 (``Modal Properties, N = ..., T1 = ...``).  These are the modal
companions to the structural tables in :mod:`generic_frame_data`
(Tables A.7--A.18).

Each table is shared by the stiff and flexible frame of a given storey count
because the reported quantities are scale-free:

* **Period ratios** ``Ti / T1`` — invariant to the absolute stiffness, so the
  ``T1 = 0.1N`` and ``T1 = 0.2N`` frames of the same ``N`` have identical
  ratios.
* **Participation factors** ``PFi`` — the mode is normalised so the first-mode
  roof displacement is ``1`` and every higher mode's largest |φ| is ``1``
  (base = 0).  ``PF1 = 3N/(2N+1)`` for the straight-line first mode.
* **Mass participation** ``MPi`` — effective modal mass as a fraction of the
  total mass (sums to ``1.0`` over the retained modes).
* **Modal damping** ``ξi`` — the Rayleigh modal damping implied by assigning
  5 % to mode 1 and the 95 %-cumulative-participation mode (§2.4.1).

The mode shapes ``mode_shapes[mode]`` are the ``φ`` values at floor levels
``1..N`` (base level ``0`` is zero and implied), one tuple per mode, in the
paper's own normalisation.
"""

